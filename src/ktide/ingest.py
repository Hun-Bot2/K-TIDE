"""Create a run from answers generated elsewhere (e.g. the professor's own notebook on Colab).

The input is the notebook's printed output (``[질문] ...\\n[답변] ...`` blocks). Questions must
match the professor's QUESTIONS list exactly and in order; answers are stored verbatim.
Environment details that could not be captured automatically are recorded as user-reported.

Usage:
    uv run python -m ktide.ingest OUTPUT.txt --condition B0 --tag colab-official \
        --model-zip qwen25_baseline_v2.zip --gpu "Colab default GPU (user-reported)"
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from ktide.artifacts import Prediction, new_run_dir, sha256_json, write_json
from ktide.generate import build_questions, judge_input_text
from ktide.metrics import answer_metrics
from ktide.professor import load_professor_notebook

_BLOCK = re.compile(r"\[질문\] (.*?)\n\[답변\] (.*?)(?=\n\n\[질문\] |\s*\Z)", re.S)


def parse_printed_output(text: str) -> list[tuple[str, str]]:
    pairs = [(q.strip(), a.strip()) for q, a in _BLOCK.findall(text.strip() + "\n")]
    if not pairs:
        raise ValueError("no [질문]/[답변] blocks found")
    return pairs


def sha256_file(path: Path) -> str:
    d = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 24), b""):
            d.update(block)
    return d.hexdigest()


def main(argv: list[str] | None = None) -> Path:
    ap = argparse.ArgumentParser()
    ap.add_argument("output_txt", type=Path)
    ap.add_argument("--experiment", default="baseline")
    ap.add_argument("--condition", default="B0")
    ap.add_argument("--tag", default="colab-official")
    ap.add_argument("--model-zip", type=Path, default=None)
    ap.add_argument("--model-note", default="")
    ap.add_argument("--gpu", default="unknown (user-reported)")
    ap.add_argument("--notes", default="")
    args = ap.parse_args(argv)

    nb = load_professor_notebook()
    pairs = parse_printed_output(args.output_txt.read_text(encoding="utf-8"))
    got_q = [q for q, _ in pairs]
    if got_q != [q.strip() for q in nb.questions]:
        raise ValueError("questions in output do not match the professor's QUESTIONS (order/text)")

    questions = build_questions(nb.questions, prefix="PUB")
    answers = [a for _, a in pairs]
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained("Qwen/Qwen2.5-1.5B-Instruct")
    max_new = nb.constants["MAX_NEW_TOKENS"]

    run_id, out = new_run_dir(args.experiment, args.condition, args.tag)
    model_ref = {"source": "user-built submission ZIP", "note": args.model_note}
    if args.model_zip:
        model_ref |= {
            "zip_name": args.model_zip.name,
            "zip_sha256": sha256_file(args.model_zip),
            "zip_bytes": args.model_zip.stat().st_size,
        }
    config = {
        "experiment": args.experiment,
        "condition": args.condition,
        "run_id": run_id,
        "official_conditions": True,
        "provenance": "ingested: generated by the unmodified professor notebook; answers pasted "
        "by the user from the notebook's printed output",
        "model": model_ref,
        "dataset": {
            "name": "professor_public",
            "source": "professor_notebook",
            "n": len(questions),
            "sha256": sha256_json([q.model_dump() for q in questions]),
        },
        "inference": {
            "code": "professor notebook (unmodified), executed by the user on Colab",
            "professor_notebook_sha256": nb.sha256,
            "system_prompt": nb.system_prompt,
            "max_new_tokens": max_new,
            "batch_size": nb.constants["BATCH_SIZE"],
            "device": "cuda:0 (per notebook load_model)",
            "dtype": "torch.float16",
            "attn_implementation": "sdpa",
            "padding_side": "left",
        },
        "seed": None,
        "notes": args.notes,
        "raw_output_sha256": sha256_file(args.output_txt),
    }
    write_json(out / "config.json", config)
    write_json(
        out / "environment.json",
        {
            "captured": False,
            "gpu": args.gpu,
            "platform": "Google Colab (user-reported)",
            "pinned_by_notebook": {
                "transformers": "4.57.1",
                "accelerate": "1.11.0",
                "huggingface_hub": "0.36.0",
                "safetensors": "0.6.2",
            },
            "torch": "Colab preinstalled (not reported)",
        },
    )
    write_json(out / "questions.json", [q.model_dump() for q in questions])
    write_json(out / "answers.json", answers)
    preds, rows = [], []
    for i, (q, a) in enumerate(zip(questions, answers, strict=True), 1):
        preds.append(
            Prediction(
                question_number=i,
                question_id=q.question_id,
                question=q.question,
                answer=a,
                word_count=len(a.split()),
                generation_status="success" if a.strip() else "empty",
            )
        )
        n_tok = len(tok(a, add_special_tokens=False).input_ids)
        rows.append(
            {
                "question_number": i,
                "question_id": q.question_id,
                **answer_metrics(a, n_tok, max_new),
            }
        )
    write_json(out / "predictions.json", [p.model_dump() for p in preds])
    write_json(out / "rule_metrics.json", rows)
    (out / "judge_input.txt").write_text(judge_input_text(preds), encoding="utf-8")
    print(f"[ingested] {len(answers)} answers -> {out}")
    return out


if __name__ == "__main__":
    main()
